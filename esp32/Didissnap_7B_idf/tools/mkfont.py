#!/usr/bin/env python3
"""ทำฟอนต์ LVGL 9 (lv_font_fmt_txt, 4 bpp) จากไฟล์ TTF ด้วย Pillow — ใช้แทน lv_font_conv
   python3 mkfont.py font.ttf size name "chars" out.c
   chars: ตัวอักษรที่ต้องการ (รองรับช่วง เช่น "\x20-\x7e")"""
import sys
from PIL import Image, ImageDraw, ImageFont

def expand(spec):
    out, i = [], 0
    while i < len(spec):
        if i + 2 < len(spec) and spec[i + 1] == '-' and spec[i + 2] != '\0':
            out += [chr(c) for c in range(ord(spec[i]), ord(spec[i + 2]) + 1)]
            i += 3
        else:
            out.append(spec[i]); i += 1
    return sorted(set(out), key=ord)

def main():
    ttf, size, name, spec, outp = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5]
    spec = spec.encode().decode('unicode_escape').encode('latin1').decode('utf-8')
    f = ImageFont.truetype(ttf, size, layout_engine=ImageFont.Layout.BASIC)
    asc, desc = f.getmetrics()
    chars = [c for c in expand(spec)]
    bitmap, dsc = bytearray(), []
    for ch in chars:
        adv = int(round(f.getlength(ch) * 16))
        x0, y0, x1, y1 = f.getbbox(ch, anchor='ls')
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        idx = len(bitmap)
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor='ls')
            px = list(im.getdata())
            # ตัดแถว/คอลัมน์ว่าง
            nib = [p >> 4 for p in px]
            if len(nib) % 2: nib.append(0)
            for k in range(0, len(nib), 2):
                bitmap.append((nib[k] << 4) | nib[k + 1])
        else:
            w = h = 0
        dsc.append((idx, adv, w, h, x0, -y1 if h else 0))
    cps = [ord(c) for c in chars]
    start = cps[0]
    with open(outp, 'w', encoding='utf-8') as o:
        o.write('// generated by tools/mkfont.py from %s size %d\n#include "lvgl.h"\n\n' % (ttf.split('/')[-1], size))
        o.write('static LV_ATTRIBUTE_LARGE_CONST const uint8_t %s_bmp[] = {\n' % name)
        for k in range(0, len(bitmap), 24):
            o.write('  ' + ','.join(str(b) for b in bitmap[k:k + 24]) + ',\n')
        o.write('  0};\n\nstatic const lv_font_fmt_txt_glyph_dsc_t %s_gd[] = {\n  {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},\n' % name)
        for d in dsc:
            o.write('  {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d},\n' % d)
        o.write('};\n\nstatic const uint16_t %s_ul[] = {%s};\n\n' % (name, ','.join(str(c - start) for c in cps)))
        o.write('static const lv_font_fmt_txt_cmap_t %s_cm[] = {{.range_start = %d, .range_length = %d, .glyph_id_start = 1, '
                '.unicode_list = %s_ul, .glyph_id_ofs_list = NULL, .list_length = %d, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};\n\n'
                % (name, start, cps[-1] - start + 1, name, len(cps)))
        o.write('static const lv_font_fmt_txt_dsc_t %s_dsc = {.glyph_bitmap = %s_bmp, .glyph_dsc = %s_gd, .cmaps = %s_cm, '
                '.kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = 0};\n\n'
                % (name, name, name, name))
        o.write('const lv_font_t %s = {.get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt, '
                '.line_height = %d, .base_line = %d, .subpx = LV_FONT_SUBPX_NONE, .underline_position = -2, .underline_thickness = 2, '
                '.dsc = &%s_dsc, .fallback = NULL, .user_data = NULL};\n' % (name, asc + desc, desc, name))
    print('%s: %d glyphs, %d KB' % (name, len(chars), len(bitmap) // 1024))

main()

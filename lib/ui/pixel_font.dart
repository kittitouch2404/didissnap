/// ขนาดข้อความ (กว้าง, สูง) เมื่อ 1 จุด = [px]
Size pixelTextSize(String text, double px) =>
    Size(text.isEmpty ? 0 : (text.length * 6 - 1) * px, 7 * px);

/// วาดข้อความพิกเซล; [px] = ขนาด 1 จุด, [outline] = ขอบหนา 1 จุด
void drawPixelText(
  Canvas c,
  String text,
  Offset at, {
  required double px,
  Color color = Colors.white,
  Color? outline = Colors.black,
  Alignment anchor = Alignment.topLeft,
  Color? shadow,
}) {
  final t = text.toUpperCase();
  final sz = pixelTextSize(t, px);
  final o = Offset(at.dx - (anchor.x + 1) / 2 * sz.width,
      at.dy - (anchor.y + 1) / 2 * sz.height);
  final body = Path();
  final edge = Path();
  for (var i = 0; i < t.length; i++) {
    final g = _glyphs[t[i]];
    if (g == null) continue;
    final x0 = o.dx + i * 6 * px;
    for (var row = 0; row < 7; row++) {
      final line = g[row];
      for (var col = 0; col < 5; col++) {
        if (line.codeUnitAt(col) != 0x31) continue; // '1'
        final r = Rect.fromLTWH(x0 + col * px, o.dy + row * px, px, px);
        body.addRect(r);
        if (outline != null) edge.addRect(r.inflate(px));
      }
    }
  }
  if (shadow != null) {
    c.drawPath(body.shift(Offset(px, px)), Paint()..color = shadow);
  }
  if (outline != null) c.drawPath(edge, Paint()..color = outline);
  c.drawPath(body, Paint()..color = color);
}

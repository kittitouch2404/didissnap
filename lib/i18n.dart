//  - คลาส Text ด้านล่างใช้แทน Text ของ Flutter ในหน้าจอทั้งหมด (import material แบบ hide Text)
import 'package:flutter/material.dart' as m;
import 'package:flutter/widgets.dart' hide Text;

/// true = English
final ValueNotifier<bool> langEn = ValueNotifier(false);

final RegExp _thaiRun = RegExp(r'[\u0E00-\u0E7F](?:[\u0E00-\u0E7F ]*[\u0E00-\u0E7F])?');

/// แปลข้อความ (ภาษาไทยเป็นค่าเริ่มต้น)
String tr(String s) {
  if (!langEn.value || s.isEmpty) return s;
  final hit = _en[s];
  if (hit != null) return hit;
  if (!_thaiRun.hasMatch(s)) return s;
  return s.replaceAllMapped(_thaiRun, (mm) => _en[mm[0]!] ?? mm[0]!);
}

/// ให้ทั้งแอปวาดใหม่เมื่อสลับภาษา
class LangScope extends InheritedNotifier<ValueNotifier<bool>> {
  LangScope({super.key, required super.child}) : super(notifier: langEn);
  static void watch(BuildContext c) => c.dependOnInheritedWidgetOfExactType<LangScope>();
}

/// Text ที่แปลภาษาให้เอง (ใช้แทน Text ของ Flutter)
class Text extends StatelessWidget {
  const Text(this.data,
      {super.key, this.style, this.textAlign, this.maxLines, this.overflow, this.softWrap, this.textDirection});
  final String data;
  final TextStyle? style;
  final TextAlign? textAlign;
  final int? maxLines;
  final TextOverflow? overflow;
  final bool? softWrap;
  final TextDirection? textDirection;

  @override
  Widget build(BuildContext context) {
    LangScope.watch(context);
    return m.Text(tr(data),
        style: style,
        textAlign: textAlign,
        maxLines: maxLines,
        overflow: overflow,
        softWrap: softWrap,
        textDirection: textDirection);
  }
}

